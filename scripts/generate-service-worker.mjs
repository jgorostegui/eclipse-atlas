// Post-build step: writes dist/sw.js with a precache manifest of the app
// shell (index.html, hashed assets, icons). Everything else same-origin is
// cached at runtime after first use, so the heavy map overlays are never
// forced into an install. The cache version is a digest of the precached
// bytes, so an unchanged build reuses its caches and a changed one replaces
// them on activation.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");

const PRECACHE_ROOT_FILES = [
  "index.html",
  "favicon.svg",
  "favicon.ico",
  "apple-touch-icon.png",
];
const PRECACHE_DIRECTORIES = ["assets"];

function walk(directory, prefix) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const relative = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) {
      return walk(path.join(directory, entry.name), relative);
    }
    return entry.isFile() ? [relative] : [];
  });
}

if (!existsSync(path.join(dist, "index.html"))) {
  throw new Error(
    "dist/index.html is missing; run the build before generating the service worker.",
  );
}

const files = [
  ...PRECACHE_ROOT_FILES.filter((file) => existsSync(path.join(dist, file))),
  ...PRECACHE_DIRECTORIES.filter((directory) =>
    existsSync(path.join(dist, directory)),
  ).flatMap((directory) => walk(path.join(dist, directory), directory)),
].sort();

const digest = createHash("sha256");
for (const file of files) {
  digest.update(file);
  digest.update(readFileSync(path.join(dist, file)));
}
const version = digest.digest("hex").slice(0, 12);

const precacheLiteral = JSON.stringify(
  files.map((file) => `./${file}`),
  null,
  2,
);

const source = `// Generated by scripts/generate-service-worker.mjs. Do not edit by hand.
const VERSION = ${JSON.stringify(version)};
const PRECACHE = ${precacheLiteral};
const PRECACHE_CACHE = \`eclipse-atlas-precache-\${VERSION}\`;
const RUNTIME_CACHE = "eclipse-atlas-runtime-v1";
const PRECACHE_PATHS = new Set(
  PRECACHE.map((entry) => new URL(entry, self.location.href).pathname),
);

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(PRECACHE_CACHE).then((cache) => cache.addAll(PRECACHE)),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names
          .filter(
            (name) =>
              name.startsWith("eclipse-atlas-precache-") &&
              name !== PRECACHE_CACHE,
          )
          .map((name) => caches.delete(name)),
      );
      await self.clients.claim();
    })(),
  );
});

async function navigationResponse(request) {
  // Online, the page always comes from the network so a new deployment is
  // picked up immediately; offline, the precached shell answers.
  try {
    return await fetch(request);
  } catch {
    const cached = await caches.match("./index.html", { ignoreSearch: true });
    return cached ?? Response.error();
  }
}

async function precacheResponse(request) {
  const cache = await caches.open(PRECACHE_CACHE);
  const cached = await cache.match(request, { ignoreSearch: true });
  return cached ?? fetch(request);
}

async function runtimeResponse(event) {
  const runtime = await caches.open(RUNTIME_CACHE);
  const cached = await runtime.match(event.request);
  const refresh = fetch(event.request)
    .then((response) => {
      if (response.ok && response.type === "basic") {
        void runtime.put(event.request, response.clone());
      }
      return response;
    })
    .catch(() => null);
  if (cached) {
    // Serve the copy immediately and refresh it in the background.
    event.waitUntil(refresh);
    return cached;
  }
  const network = await refresh;
  return network ?? Response.error();
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // The clock probe must always reach the network: the calibration measures
  // the timing headers of the live response, and a cached stamp would poison
  // the offset.
  if (url.searchParams.has("clock-probe")) return;
  if (request.mode === "navigate") {
    event.respondWith(navigationResponse(request));
    return;
  }
  if (PRECACHE_PATHS.has(url.pathname)) {
    event.respondWith(precacheResponse(request));
    return;
  }
  event.respondWith(runtimeResponse(event));
});
`;

writeFileSync(path.join(dist, "sw.js"), source);
console.log(
  `Service worker written: ${files.length} precached files, version ${version}.`,
);
